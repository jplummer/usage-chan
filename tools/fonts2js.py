#!/usr/bin/env python3
"""Convert LovyanGFX's bundled bitmap fonts into JSON for docs/sim.

The simulator draws the device's own glyphs pixel for pixel, so the spec and
the screen share one set of faces. Run after changing FONTS below or bumping
M5GFX; the output is committed so the sim works without PlatformIO.

    python3 tools/fonts2js.py > docs/sim/fonts.js
"""
import base64, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LGFX = os.path.join(ROOT, '.pio/libdeps/stackchan/M5GFX/src/lgfx')

# GFXfont faces (Adafruit format). Each is a header under Fonts/GFXFF or
# Fonts/Custom, named after the font symbol.
GFX = ['FreeSans9pt7b', 'FreeSans12pt7b', 'FreeSans18pt7b', 'FreeSans24pt7b',
       'FreeSansBold9pt7b', 'FreeSansBold12pt7b', 'FreeSansBold18pt7b',
       'FreeSansBold24pt7b', 'DejaVu9', 'DejaVu12', 'DejaVu18']

def cpp(path):
    return subprocess.check_output(['cc', '-E', '-P', '-DPROGMEM=', path],
                                   text=True)

def ints(body):
    return [int(t, 0) for t in re.findall(r'-?0x[0-9A-Fa-f]+|-?\d+', body)]

def gfx_font(name):
    for sub in ('GFXFF', 'Custom'):
        p = os.path.join(LGFX, 'Fonts', sub, name + '.h')
        if os.path.exists(p):
            break
    src = cpp(p)
    bm = re.search(name + r'Bitmaps\[\]\s*=\s*\{(.*?)\};', src, re.S).group(1)
    gl = re.search(name + r'Glyphs\[\]\s*=\s*\{(.*?)\};', src, re.S).group(1)
    hd = re.search(r'GFXfont\s+' + name + r'\s*=\s*\{(.*?)\};', src, re.S).group(1)
    bitmap = bytes(ints(bm))
    glyphs = [ints(g) for g in re.findall(r'\{([^{}]*)\}', gl)]
    first, last, yadv = ints(hd.split(',', 2)[2])[:3]
    assert len(glyphs) == last - first + 1, name
    return {'type': 'gfx', 'first': first, 'last': last, 'yAdvance': yadv,
            'glyphs': glyphs, 'bitmap': base64.b64encode(bitmap).decode()}

def font2():
    src = cpp(os.path.join(LGFX, 'Fonts', 'Font16.h'))
    widths = ints(re.search(r'widtbl_f16\[96\]\s*=\s*\{(.*?)\};', src, re.S).group(1))
    chars = {}
    for m in re.finditer(r'chr_f16_([0-9A-F]{2})\[\d+\]\s*=\s*\{(.*?)\};', src, re.S):
        chars[int(m.group(1), 16)] = bytes(ints(m.group(2)))
    rows = b''.join(chars[c] for c in range(0x20, 0x80))
    return {'type': 'bmp', 'height': 16, 'baseline': 13, 'widths': widths,
            'rows': base64.b64encode(rows).decode()}

fonts = {'Font2': font2()}
for n in GFX:
    fonts[n] = gfx_font(n)
sys.stdout.write('// Generated by tools/fonts2js.py from M5GFX. Do not edit.\n')
sys.stdout.write('window.LGFX_FONTS = ' + json.dumps(fonts, separators=(',', ':')) + ';\n')
